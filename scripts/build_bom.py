#!/usr/bin/env python3
"""Build BOM.md from the procurement records of the build pack plus 0-procurement/foundation-additions.json.

Reads (read only), under --robotics <microduck-sim>/build-pack-20260913/procurement/:
  bom.json            105 items: model, installed quantity, category, sourcing decision, store, unit price, link
  catalog-en.json     the same items with English notes (used for the role text)
  cart-plan.json      per-item cart classification (used for the quoted subtotal when the item was bought)
  sourcing-policy.json  the holds: review_hold, borrow_first, club_supply, included, owned

Writes BOM.md next to this script's parent and 0-procurement/bom-source.json (the merged rows, no order data).
Order numbers, receipts, addresses, account names and cart URLs are never copied: only store, model, quantity,
unit price and the public product link.

Run:  python3 scripts/build_bom.py --robotics ~/code/robotics/microduck-sim
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent

SECTIONS = [
    ('in use', 'Bought or supplied for this robot and on it now'),
    ('battery route', 'Battery route (D-010): bought, backpack being built, not yet on the robot'),
    ('club', 'From the CMU RoboClub drawers (not bought; club supply)'),
    ('tools', 'Tools and bench equipment (borrowed, not bought)'),
    ('replaced', 'Bought earlier, replaced before the foundation'),
    ('not used', 'Bought or supplied earlier, not on the foundation robot'),
    ('not bought', 'Not bought: sourcing-policy hold, optional, or not needed by the current design'),
]

TOOL_IDS = {'computer', 'network', 'printer', 'caliper', 'scale', 'screwdriver', 'solder_station', 'wire_tools',
            'heat_tool', 'meter', 'fume_extractor', 'bench_supply', 'hand_tools', 'power_test_instruments',
            'wire_labels', 'sd_reader'}


def money(v):
    return f'${v:,.2f}' if isinstance(v, (int, float)) and v else ('included' if v == 0 else 'not recorded')


def section_of(item, decision, override):
    if override and override.get('foundation'):
        return override['foundation']
    if item['id'] in TOOL_IDS:
        return 'tools'
    if decision in ('review_hold', 'optional'):
        return 'not bought'
    if decision == 'club_supply':
        return 'club'
    if decision in ('borrow_first', 'owned', 'included', 'buy'):
        return 'in use' if item.get('required_current_design', True) else 'not bought'
    return 'in use'


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--robotics', type=Path, required=True)
    args = ap.parse_args()
    proc = args.robotics / 'build-pack-20260913' / 'procurement'
    bom = json.loads((proc / 'bom.json').read_text())
    catalog = {e['id']: e for e in json.loads((proc / 'catalog-en.json').read_text())}
    plan = {e['item_id']: e for e in json.loads((proc / 'cart-plan.json').read_text())['all_item_classifications']}
    policy = json.loads((proc / 'sourcing-policy.json').read_text())
    extra = json.loads((ROOT / '0-procurement' / 'foundation-additions.json').read_text())
    overrides = extra['overrides']

    rows = []
    for item in bom['items']:
        p = item.get('purchase') or {}
        decision = (item.get('sourcing') or {}).get('decision') or (policy['items'].get(item['id']) or {}).get('decision')
        ov = overrides.get(item['id'])
        cat = catalog.get(item['id'], {})
        role = (cat.get('role_zh') or item.get('role_zh') or '').strip()
        qty = item.get('installed_quantity')
        rows.append({
            'id': item['id'],
            'model': item['model'],
            'quantity': qty if qty not in (None, 0) else (plan.get(item['id'], {}).get('quantity') or 'as needed'),
            'unit': item.get('unit', ''),
            'store': p.get('store') or ('kit' if decision == 'included' else ''),
            'url': p.get('url'),
            'unit_price_usd': p.get('unit_price_usd'),
            'package_quantity': p.get('package_content_quantity'),
            'decision': decision,
            'role': role,
            'note': (ov or {}).get('note', ''),
            'section': section_of(item, decision, ov),
        })
    for a in extra['additions']:
        rows.append({'id': a['id'], 'model': a['model'], 'quantity': a['quantity'], 'unit': a['unit'], 'store': a['store'],
                     'url': a.get('url'), 'unit_price_usd': a.get('unit_price_usd'), 'package_quantity': 1,
                     'decision': 'foundation addition', 'role': '', 'note': a.get('note', ''), 'section': a['foundation']})

    (ROOT / '0-procurement' / 'bom-source.json').write_text(json.dumps(rows, indent=1, ensure_ascii=False) + '\n')

    L = ['# Bill of materials, CMU MicroDuck foundation (2026-10-23)', '',
         'Generated by `scripts/build_bom.py` from the project\'s procurement records (`bom.json`, `catalog-en.json`, '
         '`cart-plan.json`, `sourcing-policy.json`, prices as read on the dates recorded there, mostly September and '
         'October 2026) and `0-procurement/foundation-additions.json` for the parts bought after those records. '
         'Prices are what the records hold, not current quotes. Order numbers and receipts are not published. '
         'The sourcing policy of the project is kept: a part on hold or marked club supply was not bought, and this '
         'list does not ask you to buy it either; the CMU RoboClub drawers supplied screws, wire and consumables.', '',
         'The role text of the club-drawer and tool rows is the September 2026 record and some of it describes the harness of that '
         'time (12 V, SMPS2DXL, Raspberry Pi); the part and quantity columns are what the robot uses. Printed parts are in '
         '`1-printing/`. Servo count, roles and IDs are in `2-servos-openrb/`.', '']
    for key, title in SECTIONS:
        sel = [r for r in rows if r['section'] == key]
        if not sel:
            continue
        L.append(f'## {title}')
        L.append('')
        L.append('| Part | Qty | Store | Unit price | Link | Note |')
        L.append('|---|---|---|---|---|---|')
        for r in sorted(sel, key=lambda r: r['id']):
            link = f"[link]({r['url']})" if r['url'] else ''
            qty = f"{r['quantity']} {r['unit']}".strip()
            price = money(r['unit_price_usd'])
            if r.get('package_quantity') and r['package_quantity'] not in (1, None) and r['unit_price_usd']:
                price += f" per pack of {r['package_quantity']}"
            note = r['note'] or r['role']
            L.append(f"| {r['model'].replace('|', '/')} | {qty} | {r['store'] or ''} | {price} | {link} | {note.replace('|', '/')} |")
        L.append('')
    (ROOT / 'BOM.md').write_text('\n'.join(L) + '\n')
    print(json.dumps({'rows': len(rows), 'by_section': {k: sum(1 for r in rows if r['section'] == k) for k, _ in SECTIONS}}))


if __name__ == '__main__':
    main()
